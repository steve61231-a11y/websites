// Turn a folder of screenshots into course thumbnails.
//
//   node scripts/import-thumbnails.mjs <folder> [course-id]      (default: the-prod)
//
// Name each image after what it's for (any image format; extra words are ignored):
//   2.3.png  or  "2.3 - Camera Sensor.jpg"   → video 2.3's thumbnail
//   "2.4 and 2.5.jpg"                        → the same image for 2.4 and 2.5
//   day-2.jpg / day_2.jpg                    → Day 2's cover
//   intro.jpg / conclusion.jpg               → Introduction / Conclusion cover
//   cover.jpg                                → the course card and page cover
//
// Images keep their full frame (no cropping), are capped at 1920 px wide and saved as JPEG in
// public/thumbs/<course>/. Then src/lib/content/<course>/thumbnails.ts is
// regenerated from everything in that folder, so re-running only adds or
// replaces the images you give it.
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const [src, course = "the-prod"] = process.argv.slice(2);
if (!src) {
  console.error("Usage: node scripts/import-thumbnails.mjs <folder> [course-id]");
  process.exit(1);
}
const outDir = path.join("public", "thumbs", course);
mkdirSync(outDir, { recursive: true });

/** Where an image goes. One image can serve several videos: "2.4 and 2.5.jpg". */
function keysFor(file) {
  const name = path.parse(file).name.toLowerCase().trim();
  const codes = [...name.matchAll(/(\d+)\s*\.\s*(\d+)/g)].map((m) => `${m[1]}-${m[2]}`);
  if (codes.length) return codes;
  let m = name.match(/^day[\s_-]*(\d+)/);
  if (m) return [`day-${m[1]}`];
  if (/^(intro|welcome)/.test(name)) return ["welcome"];
  if (/^(conclusion|wrap)/.test(name)) return ["wrap-up"];
  if (/^cover/.test(name)) return ["cover"];
  return [];
}

let count = 0;
for (const file of readdirSync(src)) {
  if (!/\.(jpe?g|png|webp|avif|tiff?|heic)$/i.test(file)) continue;
  const keys = keysFor(file);
  if (!keys.length) {
    console.warn(`skip ${file}: name it like "2.3.png", "2.4 and 2.5.jpg", "day-2.jpg" or "cover.jpg"`);
    continue;
  }
  for (const key of keys) {
    await sharp(path.join(src, file))
      .rotate()
      .resize({ width: 1920, withoutEnlargement: true }) // keep the full frame, never upscale
      .jpeg({ quality: 88, mozjpeg: true })
      .toFile(path.join(outDir, `${key}.jpg`));
    console.log(`${file} → ${outDir}/${key}.jpg`);
    count++;
  }
}

// Regenerate the map from every thumbnail on disk.
const lessons = {};
const days = {};
let cover = null;
for (const file of readdirSync(outDir).sort()) {
  const key = path.parse(file).name;
  const url = `/thumbs/${course}/${file}`;
  if (/^\d+-\d+$/.test(key)) lessons[key.replace("-", ".")] = url;
  else if (key === "cover") cover = url;
  else days[key] = url;
}
const ts = `// Generated by scripts/import-thumbnails.mjs. Re-run it to change; don't edit by hand.

/** Video thumbnails, keyed by video number. */
export const lessonThumbs: Record<string, string> = ${JSON.stringify(lessons, null, 2)};

/** Day covers, keyed by module id. */
export const dayCovers: Record<string, string> = ${JSON.stringify(days, null, 2)};

/** Course card and page cover. */
export const courseCover: string | null = ${JSON.stringify(cover)};
`;
writeFileSync(path.join("src", "lib", "content", course, "thumbnails.ts"), ts);
console.log(`\n${count} image(s) imported. ${Object.keys(lessons).length} video thumbnails, ${Object.keys(days).length} day covers${cover ? ", course cover" : ""}.`);
